import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import solc from "solc";

const require = createRequire(import.meta.url);
const output = JSON.parse(solc.compile(JSON.stringify({
  language: "Solidity",
  sources: { "funding_campaign.sol": {
    content: readFileSync(new URL("../../smart_contracts/funding_campaign.sol", import.meta.url), "utf8")
  } },
  settings: {
    optimizer: { enabled: true, runs: 200 }, viaIR: true, evmVersion: "cancun",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object", "evm.deployedBytecode.immutableReferences"] } }
  }
}), { import: (path) => {
  try { return { contents: readFileSync(require.resolve(path), "utf8") }; }
  catch { return { error: `Import not found: ${path}` }; }
} }));
const errors = (output.errors || []).filter((entry) => entry.severity === "error");
if (errors.length) throw new Error(errors.map((entry) => entry.formattedMessage).join("\n"));
const contract = output.contracts["funding_campaign.sol"].FundingCampaign;
const artifact = {
  abi: contract.abi,
  bytecode: `0x${contract.evm.bytecode.object}`,
  runtime: `0x${contract.evm.deployedBytecode.object}`,
  immutableReferences: contract.evm.deployedBytecode.immutableReferences
};
mkdirSync(new URL("../src/generated/", import.meta.url), { recursive: true });
writeFileSync(new URL("../src/generated/funding-campaign.js", import.meta.url),
  `// Generated by npm run compile:funding. Do not edit manually.\nexport default ${JSON.stringify(artifact)};\n`);
console.log("Compiled FundingCampaign for browser deployment and verification.");
